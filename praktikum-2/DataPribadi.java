public class DataPribadi {
    public static void main(String[] args) {
        // Deklarasi variabel data pribadi
        int umur = 19;                  // tipe int
        double tinggiBadan = 155.5;     // tipe double
        char inisial = 'A';             // tipe char
        boolean mahasiswaAktif = true;  // tipe boolean

        // Cetak seluruh variabel
        System.out.println("Umur: " + umur + " tahun");
        System.out.println("Tinggi Badan: " + tinggiBadan + " cm");
        System.out.println("Inisial: " + inisial);
        System.out.println("Mahasiswa Aktif: " + mahasiswaAktif);
    }
}